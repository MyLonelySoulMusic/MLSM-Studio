import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { FullVideoPreview } from './FullVideoPreview';
import { lastFrame } from './render';
import { newFormat } from './model';
vi.mock('./render', () => ({ lastFrame: vi.fn().mockResolvedValue(new File([''], 'still.png')) }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); Reflect.deleteProperty(HTMLVideoElement.prototype, 'requestVideoFrameCallback'); Reflect.deleteProperty(HTMLVideoElement.prototype, 'cancelVideoFrameCallback'); });
it('previews the trimmed source, reaction and next column on one continuous timeline', async () => {
  URL.createObjectURL = vi.fn(() => 'blob:preview'); URL.revokeObjectURL = vi.fn();
  vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
  vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue(undefined);
  const format = newFormat();
  format.uploads = ['a', 'b'].map(id => ({ id, name: id, description: '', duration: 10, trimIn: 2, stopSeconds: 5, reactionId: 'r', rowId: 'row', file: new File([''], `${id}.mp4`) }));
  format.library = [{ id: 'r', name: 'Reaction', description: '', duration: 5, trimIn: 1, trimOut: 3, file: new File([''], 'r.mp4') }];
  const { container } = render(<FullVideoPreview format={format} activeId="a" language="it" />);
  expect(screen.getByLabelText('Posizione nel video completo')).toHaveAttribute('max', '10');
  let video = container.querySelector('video')!;
  fireEvent.loadedMetadata(video); fireEvent.loadedData(video); expect(video.currentTime).toBe(2);
  fireEvent.click(screen.getByRole('button', { name: 'Riproduci tutto' }));
  video.currentTime = 5; fireEvent.timeUpdate(video);
  video = container.querySelector('video')!; fireEvent.loadedMetadata(video); fireEvent.loadedData(video); expect(video.currentTime).toBe(1);
  await waitFor(() => expect(container.querySelector('.vfb-preview-still img')).toBeInTheDocument());
  fireEvent.load(container.querySelector('.vfb-preview-still img')!);
  video.currentTime = 3; fireEvent.timeUpdate(video);
  video = container.querySelector('video')!; fireEvent.loadedMetadata(video); fireEvent.loadedData(video); expect(video.currentTime).toBe(2);
  expect(screen.getByLabelText('Posizione nel video completo')).toHaveValue('5');
});

it('prepares the second freeze in advance and waits for its image before playing the reaction', async () => {
  URL.createObjectURL = vi.fn(() => 'blob:preview'); URL.revokeObjectURL = vi.fn();
  vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
  const play = vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue(undefined);
  let resolveSecond!: (file: File) => void;
  vi.mocked(lastFrame).mockResolvedValueOnce(new File([''], 'first.png')).mockImplementationOnce(() => new Promise(resolve => { resolveSecond = resolve; }));
  const format = newFormat();
  format.uploads = ['a', 'b'].map(id => ({ id, name: id, description: '', duration: 10, trimIn: 2, stopSeconds: 5, reactionId: 'r', rowId: 'row', file: new File([''], `${id}.mp4`) }));
  format.library = [{ id: 'r', name: 'Reaction', description: '', duration: 5, trimIn: 1, trimOut: 3, file: new File([''], 'r.mp4') }];
  const { container } = render(<FullVideoPreview format={format} activeId="a" language="it" />);
  expect(lastFrame).toHaveBeenCalledWith(format.uploads[1]!.file, 5);
  fireEvent.change(screen.getByLabelText('Posizione nel video completo'), { target: { value: '8' } });
  fireEvent.loadedMetadata(container.querySelector('video')!); fireEvent.loadedData(container.querySelector('video')!);
  fireEvent.click(screen.getByRole('button', { name: 'Riproduci tutto' }));
  expect(play).not.toHaveBeenCalled();
  await act(async () => resolveSecond(new File([''], 'second.png')));
  expect(play).not.toHaveBeenCalled();
  fireEvent.load(container.querySelector('.vfb-preview-still img')!);
  await waitFor(() => expect(play).toHaveBeenCalledTimes(1));
  expect(container.querySelector('video')!.currentTime).toBe(1);
});

it('waits for a decoded frame at the trim point and uses the video frame clock for cuts', async () => {
  URL.createObjectURL = vi.fn(file => `blob:${(file as File).name}`); URL.revokeObjectURL = vi.fn();
  vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
  const play = vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue(undefined);
  let frame!: VideoFrameRequestCallback;
  Object.defineProperty(HTMLVideoElement.prototype, 'requestVideoFrameCallback', { configurable: true, value: (callback: VideoFrameRequestCallback) => { frame = callback; return 1; } });
  Object.defineProperty(HTMLVideoElement.prototype, 'cancelVideoFrameCallback', { configurable: true, value: () => {} });
  const format = newFormat();
  format.uploads = ['a', 'b'].map(id => ({ id, name: id, description: '', duration: 10, trimIn: 2, stopSeconds: 5, rowId: 'row', file: new File([''], `${id}.mp4`) }));
  const { container } = render(<FullVideoPreview format={format} activeId="a" language="it" />);
  const first = container.querySelector('video')!;
  fireEvent.loadedMetadata(first);
  fireEvent.click(screen.getByRole('button', { name: 'Riproduci tutto' }));
  expect(play).not.toHaveBeenCalled();
  expect(first.style.visibility).toBe('hidden');
  Object.defineProperty(first, 'readyState', { value: 2 });
  fireEvent.seeked(first);
  await waitFor(() => expect(play).toHaveBeenCalledTimes(1));
  expect(first.style.visibility).toBe('visible');
  await act(async () => frame(0, { mediaTime: 5 } as VideoFrameCallbackMetadata));
  const second = container.querySelector('video')!;
  expect(second).not.toBe(first);
  expect(second.getAttribute('src')).toBe('blob:b.mp4');
  expect(second.style.visibility).toBe('hidden');
  fireEvent.loadedMetadata(second);
  expect(second.currentTime).toBe(2);
  expect(play).toHaveBeenCalledTimes(1);
  fireEvent.loadedData(second);
  await waitFor(() => expect(play).toHaveBeenCalledTimes(2));
});
